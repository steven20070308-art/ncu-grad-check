SRC = "https://course.ncu.edu.tw/static/file/14/1014/img/314/{}.pdf"


def G(gid, items, min_courses=0, min_credits=None, max_credits=None):
    """items: [(課號或以 / 分隔的可替代課號, 課名, 學分), ...]"""
    courses, names, equiv = {}, {}, []
    for codes, name, cr in items:
        cs = codes.split("/")
        for c in cs:
            courses[c] = cr
            names[c] = name
        if len(cs) > 1:
            equiv.append(cs)
    g = {"id": gid, "min_courses": min_courses, "courses": courses, "names": names}
    if equiv:
        g["equiv"] = equiv
    if min_credits:
        g["min_credits"] = min_credits
    if max_credits:
        g["max_credits"] = max_credits
    return g


